"""Public task access and the worker's executor are independent ports."""
from typing import Protocol
from ..frame.contracts import TurnRequest, Task, CancelResult, RunContext, RunResult, PageQuery, Page


class TaskExecutor(Protocol):
    def Run(self, task_id: str, context: RunContext) -> RunResult: ...


class TaskService(Protocol):
    def List(self, session_id: str, query: PageQuery = PageQuery()) -> Page: ...
    def Submit(self, request: TurnRequest) -> str: ...
    def Get(self, task_id: str) -> Task: ...
    def Cancel(self, task_id: str) -> CancelResult: ...
    def RequestStop(self) -> None: ...
    def Stop(self) -> None: ...
    def IsStopped(self) -> bool: ...


class TaskDiagnostics(Protocol):
    def Status(self) -> dict: ...
