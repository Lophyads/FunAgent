"""Consumer-specific atomic operations; a Store may implement all of them."""
from typing import Protocol, runtime_checkable
from collections.abc import Mapping
from ..frame.contracts import (SessionCreate, Session, SessionSnapshot, PageQuery,
                               HistoryQuery, Page, TurnRequest, Task, RecordScope,
                               Message, ToolResult, RunResult)


class SessionStore(Protocol):
    def CreateSession(self, request: SessionCreate) -> Session: ...
    def LoadSession(self, session_id: str) -> SessionSnapshot: ...
    def ListSessions(self, query: PageQuery) -> Page: ...
    def ReadHistory(self, session_id: str, query: HistoryQuery) -> Page: ...
    def FreezePrompt(self, session_id: str, text: str) -> str: ...


class TaskStore(Protocol):
    def ListTasks(self, session_id: str, query: PageQuery) -> Page: ...
    def FindTurn(self, request: TurnRequest) -> Task | None: ...
    def RegisterTurn(self, request: TurnRequest) -> Task: ...
    def BeginTurn(self, task_id: str) -> SessionSnapshot: ...
    def FinishTurn(self, task_id: str, result: RunResult) -> Task: ...
    def GetTask(self, task_id: str) -> Task: ...
    def ReviewThrough(self, task_id: str) -> int: ...
    def ObserveReviewTurn(self, task_id: str, every_turns: int = 10) -> int | None: ...
    def RepairInterrupted(self) -> int: ...


class RunJournal(Protocol):
    def AppendToolCalls(self, scope: RecordScope, message: Message) -> None: ...
    def AppendToolResult(self, scope: RecordScope, result: ToolResult) -> None: ...


class ReviewStore(Protocol):
    def ReviewRange(self, session_id: str, after_id: int, through_id: int) -> tuple[Message, ...]: ...
    def ReviewWatermark(self, session_id: str) -> int: ...
    def ReviewAnchors(self, session_id: str, through_id: int) -> tuple[Message, ...]: ...
    def AdvanceReview(self, session_id: str, expected_id: int, through_id: int) -> None: ...
    def ReviewTrigger(self, session_id: str) -> Mapping: ...


class PersistenceStore(SessionStore, TaskStore, RunJournal, ReviewStore, Protocol):
    def Close(self) -> None: ...


class NullRunJournal:
    """Ephemeral runs have no persistence resource to borrow."""
    def AppendToolCalls(self, scope: RecordScope, message: Message) -> None:
        pass

    def AppendToolResult(self, scope: RecordScope, result: ToolResult) -> None:
        pass


@runtime_checkable
class DataReadStore(Protocol):
    """Optional, table-specific read access; never an arbitrary SQL port."""
    def DataSchema(self) -> dict: ...
    def ReadTable(self, table: str, query: Mapping, *, detail: bool = False) -> dict: ...
