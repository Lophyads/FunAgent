"""Stores own physical queries and atomic writes, never a model loop."""
from typing import Protocol
from ..frame.contracts import Page, RunContext
from .contracts import (MemoryQuery, MemorySearchResult, MemoryListQuery, MemoryDraft, MemoryPatch,
                        MemoryRef, MemoryRecord, MemoryWriteReceipt, EmbeddingProfile, TopicSnapshot, TopicSelection, TopicChange, UNSET)


class Embedder(Protocol):
    profile: EmbeddingProfile

    def Embed(self, texts: tuple[str, ...], purpose: str, context: RunContext) -> tuple[tuple[float, ...], ...]: ...
    def Close(self) -> None: ...


class MemoryStore(Protocol):
    capabilities: frozenset[str]
    supported_types: frozenset[str] | None
    supports_deleted_read: bool

    def Search(self, query: MemoryQuery, context: RunContext) -> MemorySearchResult: ...
    def Close(self) -> None: ...


class WritableMemoryStore(Protocol):
    def List(self, query: MemoryListQuery, context: RunContext) -> Page: ...
    def Write(self, draft: MemoryDraft, context: RunContext) -> MemoryRecord: ...
    def Update(self, ref: MemoryRef, patch: MemoryPatch, expected_version: str, context: RunContext) -> MemoryRecord: ...
    def Delete(self, ref: MemoryRef, expected_version: str, context: RunContext) -> None: ...


class MemoryTopicReader(Protocol):
    def ReadTopics(self, source_ids: tuple[str, ...], context: RunContext) -> tuple[TopicSnapshot, ...]: ...


class MemoryReader(MemoryTopicReader, Protocol):
    def SupportedTypes(self, source_ids: tuple[str, ...], context: RunContext) -> dict[str, tuple[str, ...] | None]: ...
    def Search(self, query: MemoryQuery, context: RunContext) -> MemorySearchResult: ...
    def List(self, query: MemoryListQuery, context: RunContext) -> Page: ...


class MemoryWriter(Protocol):
    def Write(self, draft: MemoryDraft, context: RunContext, *, topic: TopicSelection) -> MemoryWriteReceipt: ...
    def Update(self, ref: MemoryRef, patch: MemoryPatch, expected_version: str, context: RunContext) -> MemoryRecord: ...
    def Delete(self, ref: MemoryRef, expected_version: str, context: RunContext) -> None: ...


class TopicReader(Protocol):
    def Snapshot(self, source_id: str) -> TopicSnapshot: ...


class TopicCatalog(TopicReader, Protocol):
    def CreateTopic(self, source_id: str, parent_id: str | None, name: str, description: str) -> TopicChange: ...
    def UpdateTopic(self, source_id: str, topic_id: str, expected_revision: int, *,
                    name=UNSET, description=UNSET, parent_id=UNSET) -> TopicChange: ...
    def DeleteTopic(self, source_id: str, topic_id: str, expected_revision: int) -> int: ...
    def Assign(self, source_id: str, record_id: str, topic_id: str, expected_revision: int | None = None) -> int: ...
    def Unassign(self, source_id: str, record_id: str) -> int: ...


class ProfileReader(Protocol):
    def GetProfile(self, context: RunContext) -> tuple[MemoryRecord, ...]: ...


class MemoryAccess(MemoryReader, MemoryWriter, ProfileReader, Protocol):
    def Check(self, source_ids: tuple[str, ...], context: RunContext) -> dict: ...


class MemoryImportAccess(Protocol):
    def Submit(self, source_id: str, raw: bytes) -> dict: ...
    def Get(self, import_id: str) -> dict: ...
    def Latest(self, source_id: str) -> dict | None: ...
    def RequestStop(self) -> None: ...
    def Stop(self) -> None: ...
    def IsStopped(self) -> bool: ...


class MemoryOperationsAccess(Protocol):
    def Check(self, source_id: str | None = None) -> dict: ...
    def Inspect(self, operation: str, query) -> dict: ...
    def DefaultSource(self) -> str | None: ...
    def Sources(self) -> list[dict]: ...
    def Search(self, query: MemoryQuery) -> dict: ...
    def List(self, query: MemoryListQuery, *, topic_id: str | None = None, unclassified: bool = False) -> dict: ...
    def Write(self, draft: MemoryDraft, request_key: str | None = None, *, topic_id: str) -> dict: ...
    def Topics(self, source_id: str) -> dict: ...
    def CreateTopic(self, source_id: str, parent_id: str | None, name: str, description: str) -> dict: ...
    def UpdateTopic(self, source_id: str, topic_id: str, expected_revision: int, **changes) -> dict: ...
    def DeleteTopic(self, source_id: str, topic_id: str, expected_revision: int) -> dict: ...
    def AssignTopic(self, ref: MemoryRef, topic_id: str, expected_revision: int) -> dict: ...
    def Request(self, action: str, ref: MemoryRef, expected_version: str, patch: MemoryPatch | None = None) -> dict: ...
    def Confirm(self, challenge_id: str, arguments_digest: str, approve: bool) -> dict: ...
    def Close(self) -> None: ...
