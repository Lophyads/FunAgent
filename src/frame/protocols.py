"""Shared use-case ports; imports here never select or construct drivers."""
from typing import Protocol
from collections.abc import Iterator
from collections.abc import Mapping
from .contracts import (ReviewJob, RunContext, RunResult, SessionCreate, Session,
                        SessionSnapshot, PageQuery, HistoryQuery, Page, Interaction, ApprovalBinding, ClarificationQuestion)
from ..model.contracts import RunEvent


class RunEventWriter(Protocol):
    def Publish(self, event: RunEvent) -> None: ...


class TaskEventReader(Protocol):
    def Subscribe(self, task_id: str, after_seq: int | None = None) -> Iterator[RunEvent]: ...
    def SubscribeSession(self, session_id: str, cursor: str | None = None) -> Iterator[dict]: ...
    def Snapshot(self, session_id: str) -> dict: ...
    def Reconcile(self, tasks) -> None: ...


class NullEventWriter:
    def Publish(self, event: RunEvent) -> None:
        pass


class ReviewExecutor(Protocol):
    def Run(self, job: ReviewJob, context: RunContext) -> RunResult: ...


class ReviewQueue(Protocol):
    def Schedule(self, session_id: str, through_message_id: int) -> None: ...
    def GetStatus(self, session_id: str) -> Mapping: ...
    def RequestStop(self) -> None: ...
    def Stop(self) -> None: ...


class SessionAccess(Protocol):
    def Create(self, request: SessionCreate) -> Session: ...
    def Load(self, session_id: str) -> SessionSnapshot: ...
    def List(self, query: PageQuery = PageQuery()) -> Page: ...
    def ReadHistory(self, session_id: str, query: HistoryQuery = HistoryQuery()) -> Page: ...
    def FreezePrompt(self, session_id: str, text: str) -> str: ...


class InteractionAccess(Protocol):
    def Wait(self, kind: str, prompt: str, context: RunContext, *, binding: ApprovalBinding | None = None,
             questions: tuple[ClarificationQuestion, ...] = ()) -> bool | Mapping: ...
    def Pending(self, task_id: str) -> tuple[Interaction, ...]: ...
    def Resolve(self, interaction_id: str, answer: bool | Mapping, *, task_id: str, run_id: str) -> None: ...
