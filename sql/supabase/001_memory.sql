-- Deploy explicitly in the Supabase SQL editor. Before FIRST deployment, change
-- vector(1024) to match your embedding model. Rerunning does not change dimensions.
-- Personal trusted-host setup: only service_role can access these records/RPCs.
begin;
create schema if not exists extensions;
create extension if not exists vector with schema extensions;
set local search_path = public, extensions, pg_catalog;

create table if not exists public.funagent_memory_entries (
    namespace text not null check (length(namespace) between 1 and 200),
    id text not null check (length(id) > 0),
    kind text not null check (kind in ('user', 'note', 'episode')),
    subject text not null check (length(subject) <= 200),
    content text not null check (length(btrim(content)) > 0 and length(content) <= 5000),
    version integer not null default 1 check (version >= 1),
    source jsonb not null check (jsonb_typeof(source) = 'object'),
    event_at text,
    created_at timestamptz not null default clock_timestamp(),
    updated_at timestamptz not null default clock_timestamp(),
    dedupe_key text not null,
    embedding vector(1024) not null check (vector_norm(embedding) > 0),
    embedding_profile text not null,
    primary key (namespace, id),
    unique (namespace, dedupe_key)
);
create index if not exists funagent_memory_recent
    on public.funagent_memory_entries(namespace, updated_at desc, id desc);
create index if not exists funagent_memory_kind_recent
    on public.funagent_memory_entries(namespace, kind, updated_at desc, id desc);

create or replace function public.funagent_memory_schema(p_namespace text, p_profile text)
returns jsonb language sql stable security invoker set search_path = public, extensions, pg_catalog as $$
    select jsonb_build_object(
        'version', 1,
        'dimensions', (select atttypmod from pg_attribute
            where attrelid = 'public.funagent_memory_entries'::regclass and attname = 'embedding'),
        'status', case when exists(select 1 from public.funagent_memory_entries
            where namespace = p_namespace and embedding_profile <> p_profile)
            then 'profile_mismatch' else 'ok' end
    );
$$;

-- One write RPC shares the same namespace lock, profile guard and row-version
-- checks for add/update/delete. IDs and dedupe keys are generated by the host.
create or replace function public.funagent_memory_write(
    p_namespace text, p_profile text, p_action text, p_data jsonb
) returns jsonb language plpgsql security invoker
set search_path = public, extensions, pg_catalog as $$
declare
    current_row public.funagent_memory_entries%rowtype;
    result_row public.funagent_memory_entries%rowtype;
    entry_id text := p_data->>'id';
    key_value text;
begin
    if p_action not in ('add', 'update', 'delete') or entry_id is null or entry_id = ''
        or p_namespace is null or p_namespace = '' or p_profile is null or p_profile = '' then
        return jsonb_build_object('status', 'invalid');
    end if;
    perform pg_advisory_xact_lock(hashtextextended('funagent_memory:' || p_namespace, 0));
    if exists(select 1 from public.funagent_memory_entries
        where namespace = p_namespace and embedding_profile <> p_profile) then
        return jsonb_build_object('status', 'profile_mismatch');
    end if;

    if p_action = 'add' then
        select * into current_row from public.funagent_memory_entries
            where namespace = p_namespace and dedupe_key = p_data->>'dedupe_key';
        if found then
            return jsonb_build_object('status', 'duplicate', 'entry',
                to_jsonb(current_row) - array['namespace','embedding','embedding_profile','dedupe_key']);
        end if;
        insert into public.funagent_memory_entries
            (namespace, id, kind, subject, content, source, event_at, dedupe_key, embedding, embedding_profile)
        values (p_namespace, entry_id, p_data->>'kind', p_data->>'subject', p_data->>'content',
            p_data->'source', p_data->>'event_at', p_data->>'dedupe_key',
            (p_data->'embedding')::text::vector, p_profile)
        returning * into result_row;
    else
        select * into current_row from public.funagent_memory_entries
            where namespace = p_namespace and id = entry_id for update;
        if not found then
            return jsonb_build_object('status', 'missing');
        end if;
        if (p_data->>'expected_version')::integer is null or (p_data->>'expected_version')::integer < 1 then
            return jsonb_build_object('status', 'invalid');
        end if;
        if current_row.version <> (p_data->>'expected_version')::integer then
            return jsonb_build_object('status', 'conflict');
        end if;
        if p_action = 'delete' then
            delete from public.funagent_memory_entries where namespace = p_namespace and id = entry_id
                returning * into result_row;
        else
            key_value := case when current_row.kind = 'episode' then current_row.dedupe_key else p_data->>'dedupe_key' end;
            if exists(select 1 from public.funagent_memory_entries
                where namespace = p_namespace and dedupe_key = key_value and id <> entry_id) then
                return jsonb_build_object('status', 'duplicate_replacement');
            end if;
            update public.funagent_memory_entries set
                subject = p_data->>'subject', content = p_data->>'content', source = p_data->'source',
                event_at = p_data->>'event_at', embedding = (p_data->'embedding')::text::vector,
                dedupe_key = key_value, version = version + 1, updated_at = clock_timestamp()
            where namespace = p_namespace and id = entry_id returning * into result_row;
        end if;
    end if;
    return jsonb_build_object('status', 'ok', 'entry',
        to_jsonb(result_row) - array['namespace','embedding','embedding_profile','dedupe_key']);
end;
$$;

-- Return limit+1 rows for the host's opaque keyset cursor. Timestamp strings
-- retain Postgres precision instead of passing through a floating-point cursor.
create or replace function public.funagent_memory_list(
    p_namespace text, p_profile text, p_kind text, p_limit integer, p_after jsonb, p_id text
) returns jsonb language plpgsql stable security invoker
set search_path = public, extensions, pg_catalog as $$
declare result jsonb;
begin
    if p_limit is null or p_limit < 1 or p_limit > 200
        or (p_kind is not null and p_kind not in ('user','note','episode')) then
        return jsonb_build_object('status', 'invalid');
    end if;
    if exists(select 1 from public.funagent_memory_entries
        where namespace = p_namespace and embedding_profile <> p_profile) then
        return jsonb_build_object('status', 'profile_mismatch');
    end if;
    select jsonb_build_object('status', 'ok',
        'total', (select count(*) from public.funagent_memory_entries
            where namespace = p_namespace and (p_kind is null or kind = p_kind) and (p_id is null or id = p_id)),
        'entries', coalesce((select jsonb_agg(row_data order by stamp desc, entry_id desc) from (
            select to_jsonb(e) - array['namespace','embedding','embedding_profile','dedupe_key'] as row_data,
                updated_at as stamp, id as entry_id
            from public.funagent_memory_entries e
            where namespace = p_namespace and (p_kind is null or kind = p_kind) and (p_id is null or id = p_id)
                and (p_after is null or (updated_at, id) < ((p_after->>'updated_at')::timestamptz, p_after->>'id'))
            order by updated_at desc, id desc limit p_limit + 1
        ) page), '[]'::jsonb)) into result;
    return result;
end;
$$;

create or replace function public.funagent_memory_search(
    p_namespace text, p_profile text, p_kind text, p_limit integer,
    p_embedding double precision[], p_min_similarity double precision
) returns jsonb language plpgsql stable security invoker
set search_path = public, extensions, pg_catalog as $$
declare
    query_vector vector := array_to_json(p_embedding)::text::vector;
    result jsonb;
    expected_dimensions integer;
begin
    select atttypmod into expected_dimensions from pg_attribute
        where attrelid = 'public.funagent_memory_entries'::regclass and attname = 'embedding';
    if p_limit is null or p_limit < 1 or p_limit > 200
        or (p_kind is not null and p_kind not in ('user','note','episode'))
        or p_min_similarity is null or p_min_similarity < -1 or p_min_similarity > 1
        or query_vector is null or vector_dims(query_vector) <> expected_dimensions or vector_norm(query_vector) = 0 then
        return jsonb_build_object('status', 'invalid');
    end if;
    if exists(select 1 from public.funagent_memory_entries
        where namespace = p_namespace and embedding_profile <> p_profile) then
        return jsonb_build_object('status', 'profile_mismatch');
    end if;
    select jsonb_build_object('status', 'ok', 'entries', coalesce(jsonb_agg(row_data order by distance, stamp desc, entry_id desc), '[]'::jsonb))
        into result from (
            select to_jsonb(e) - array['namespace','embedding','embedding_profile','dedupe_key'] as row_data,
                embedding <=> query_vector as distance, updated_at as stamp, id as entry_id
            from public.funagent_memory_entries e
            where namespace = p_namespace and (p_kind is null or kind = p_kind)
                and 1 - (embedding <=> query_vector) >= p_min_similarity
            order by embedding <=> query_vector, updated_at desc, id desc limit p_limit
        ) hits;
    return result;
end;
$$;

alter table public.funagent_memory_entries enable row level security;
revoke all on public.funagent_memory_entries from public, anon, authenticated;
grant select, insert, update, delete on public.funagent_memory_entries to service_role;
revoke all on function public.funagent_memory_schema(text,text) from public, anon, authenticated;
revoke all on function public.funagent_memory_write(text,text,text,jsonb) from public, anon, authenticated;
revoke all on function public.funagent_memory_list(text,text,text,integer,jsonb,text) from public, anon, authenticated;
revoke all on function public.funagent_memory_search(text,text,text,integer,double precision[],double precision) from public, anon, authenticated;
grant execute on function public.funagent_memory_schema(text,text) to service_role;
grant execute on function public.funagent_memory_write(text,text,text,jsonb) to service_role;
grant execute on function public.funagent_memory_list(text,text,text,integer,jsonb,text) to service_role;
grant execute on function public.funagent_memory_search(text,text,text,integer,double precision[],double precision) to service_role;
grant usage on schema extensions to service_role;
notify pgrst, 'reload schema';
commit;
